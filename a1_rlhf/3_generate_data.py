"""
This file is used to generate responses for each of the five models (base, SFT, DPO, GRPO, SimPO) to the same question.
100 samples are generated for each model with a maximum sequence length of 2048. These are saved to a csv file, ready to
be ingested by 4_pairwise_eval.py.
"""

import os
from unsloth import FastLanguageModel

import csv
import gc
import torch
from datasets import load_dataset

# map model to easily identifiable name.
MODELS_TO_TEST = {
    "Model_Base": "unsloth/Llama-3.2-3B-Instruct-bnb-4bit",
    "Model_SFT": "Llama-3.2-SFT-Merged",
    "Model_DPO": "Llama-3.2-DPO-Final",
    "Model_GRPO": "Llama-3.2-GRPO-Final",
    "Model_SimPO": "Llama-3.2-SimPO-Final",
}

# set number of samples generated by each model to 100 and the maximum sequence length to 2048. This is because the generated
# output for both models will max at 4096.
results_file = "Model_Comparison_Arena.csv"
num_test_samples = 100
max_seq_length = 2048

# Call test set for sampling.
print("Fetching the unseen test split...")
dataset = load_dataset(
    "Vanessasml/cybersecurity_32k_instruction_input_output", split="train"
)
dataset = dataset.train_test_split(test_size=0.1, seed=3407)
unseen_test_set = dataset["test"]

sample_set = unseen_test_set.shuffle(seed=42).select(range(num_test_samples))

# Initialise output list.
results = []
for item in sample_set:
    prompt_text = item["instruction"]
    if item.get("input") and str(item["input"]).strip():
        prompt_text += f"\nContext: {item['input']}"

    row_data = {"prompt": prompt_text, "expected_answer": item["output"]}
    for model_name in MODELS_TO_TEST.keys():
        row_data[model_name] = ""

    results.append(row_data)

# Model generation loop.
for model_name, model_path in MODELS_TO_TEST.items():
    if model_name != "Model_Base" and not os.path.exists(model_path):
        print(f"\n[SKIPPING] {model_name} - Folder not found at: {model_path}")
        continue

    print(f"\n{'='*50}\nLoading {model_name} into VRAM...\n{'='*50}")
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=model_path,
        max_seq_length=max_seq_length,
        load_in_4bit=True,
        dtype=torch.bfloat16,
    )
    # Set unsloth to inference mode.
    FastLanguageModel.for_inference(model)

    print(f"Generating {num_test_samples} answers for {model_name}...")

    # feed instruction to model.
    for i, item in enumerate(results):
        prompt = f"Instruction: {item['prompt']}\n\nResponse: "
        inputs = tokenizer([prompt], return_tensors="pt").to("cuda")

        with torch.inference_mode():
            outputs = model.generate(
                **inputs,
                max_new_tokens=512,
                use_cache=True,
                temperature=0.2,
                top_p=0.9,
                pad_token_id=tokenizer.eos_token_id,
            )

        # decode batch from token to text and save to list.
        response = tokenizer.batch_decode(outputs, skip_special_tokens=True)[0]
        model_answer = response.split("Response: ")[-1].strip()

        results[i][model_name] = model_answer

        # Delete variables to save memory.
        del inputs
        del outputs

        if (i + 1) % 10 == 0:
            print(f"  Processed {i+1}/{num_test_samples}")
            # Flush VRAM to save memory.
            torch.cuda.empty_cache()

    # Remove model and tokeniser once generation is completed to ensure it's ready for the next model.
    print(f"Clearing {model_name} from VRAM...")
    del model
    del tokenizer
    torch.cuda.empty_cache()
    gc.collect()

# Export results csv, ready for ingestion to 4_pairwise_eval.py.
print(f"\nExporting Arena Results to {results_file}...")
fieldnames = ["prompt", "expected_answer"] + list(MODELS_TO_TEST.keys())

with open(results_file, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(results)

print("Generation complete. CSV is ready for Pairwise Tournament.")
