import torch
import csv
from datasets import load_dataset
from unsloth import FastLanguageModel

# 1. Configuration
model_path = "Llama-3.2-SFT-merged" # Your successfully trained model
results_file = "mmlu_security_results_llama.csv"
max_seq_length = 512

print(f"Loading {model_path} into VRAM for MMLU Evaluation...")
model, tokenizer = FastLanguageModel.from_pretrained(
    model_name=model_path,
    max_seq_length=max_seq_length,
    load_in_4bit=True,
    fast_inference=True,
)

# Enable native inference speed (Makes generation 2x faster)
FastLanguageModel.for_inference(model)

# 2. Load the Official MMLU Computer Security Benchmark
print("Downloading the MMLU Computer Security test set...")
dataset = load_dataset("cais/mmlu", "computer_security", split="test")
print(f"Loaded {len(dataset)} professional test questions.")

# Helper dictionary to map MMLU's integer answers (0,1,2,3) to letters
letter_map = {0: "A", 1: "B", 2: "C", 3: "D"}

correct_answers = 0
results = []

# 3. The Evaluation Loop
print("\nStarting automated grading...")
for i, item in enumerate(dataset):
    question = item["question"]
    choices = item["choices"]
    
    # MMLU gives answers as integers. We need the actual letter for grading.
    expected_letter = letter_map[item["answer"]]
    
    # Format the prompt as a strict multiple-choice test
    prompt = f"""Instruction: Answer the following multiple choice question by replying with exactly one letter (A, B, C, or D).

Question: What is the standard port for HTTP?
A. 21
B. 22
C. 80
D. 443
Response: C

Question: {question}
A. {choices[0]}
B. {choices[1]}
C. {choices[2]}
D. {choices[3]}

Response: """

    inputs = tokenizer([prompt], return_tensors="pt").to("cuda")
    
    # 4. Generate the Answer
    # We restrict max_new_tokens to 5 to prevent it from rambling.
    # Temperature 0.0 forces the absolute most mathematically likely answer.
    outputs = model.generate(
        **inputs, 
        max_new_tokens=5, 
        use_cache=True, 
        temperature=0.0, 
    )
    
    # Extract just the new text generated by the model
    response = tokenizer.batch_decode(outputs, skip_special_tokens=True)[0]
    raw_answer = response.split("Response: ")[-1].strip().upper()
    
    # Robust parsing: grab the very first character (in case it says "A." or "A)")
    model_letter = raw_answer[0] if len(raw_answer) > 0 else "X"
    
    # 5. Grade it
    is_correct = (model_letter == expected_letter)
    status = "PASSED" if is_correct else "FAILED"
    
    if is_correct:
        correct_answers += 1
        
    print(f"Q{i+1}: {status} | Model guessed: {model_letter} | Expected: {expected_letter}")
    
    # Save to the audit log
    results.append({
        "question": question,
        "model_guessed": model_letter,
        "expected_answer": expected_letter,
        "status": status
    })

# 6. Calculate Final Score
accuracy = (correct_answers / len(dataset)) * 100
print("\n" + "="*50)
print(f"FINAL MMLU COMPUTER SECURITY ACCURACY: {accuracy:.2f}%")
print(f"Passed: {correct_answers} / {len(dataset)}")
print("="*50)

# 7. Export the Audit Log
with open(results_file, 'w', newline='', encoding='utf-8') as f:
    writer = csv.DictWriter(f, fieldnames=["question", "model_guessed", "expected_answer", "status"])
    writer.writeheader()
    writer.writerows(results)

print(f"\nDetailed evaluation log saved to {results_file}.")
